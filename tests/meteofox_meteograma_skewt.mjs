import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
try{
 const page=await browser.newPage({viewport:{width:1440,height:900}});
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));

 const calls=[];
 await page.route('https://api.open-meteo.com/v1/forecast?*',async route=>{
  const url=new URL(route.request().url());
  const lat=Number(url.searchParams.get('latitude'));
  calls.push(lat);
  const base=new Date();base.setUTCHours(0,0,0,0);
  const time=Array.from({length:168},(_,i)=>new Date(base.getTime()+i*3600000).toISOString().slice(0,16));
  const temp=lat>40?10:lat<34?24:16;
  const h={time};
  for(const [key,baseValue] of Object.entries({temperature_2m:temp,relative_humidity_2m:80,apparent_temperature:temp-1,precipitation:0.25,precipitation_probability:20,wind_speed_10m:12,wind_direction_10m:270,wind_gusts_10m:22,pressure_msl:1018,dew_point_2m:10,cloud_cover:70,weather_code:3})){
   h[key]=time.map(()=>baseValue);
  }
  const days=Array.from({length:7},(_,i)=>new Date(base.getTime()+i*86400000).toISOString().slice(0,10));
  const daily={time:days,temperature_2m_max:days.map(()=>temp+2),temperature_2m_min:days.map(()=>temp-2),precipitation_sum:days.map(()=>2),precipitation_probability_max:days.map(()=>40),uv_index_max:days.map(()=>3),weather_code:days.map(()=>3)};
  await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({current:{time:new Date().toISOString().slice(0,16),temperature_2m:temp,apparent_temperature:temp-1,relative_humidity_2m:80,precipitation:0.25,wind_speed_10m:12,wind_gusts_10m:22},hourly:h,daily})});
 });
 await page.goto('http://127.0.0.1:8765/index.html',{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>document.getElementById('meteoPreview')?.disabled===false,{timeout:20000});
 assert.equal(await page.locator('#meteoSmallSvg rect').count()>5,true,'SVG do meteograma deve estar preenchido');
 assert.equal(await page.locator('#meteoSmallSvg text').count()>100,true);
 assert.equal(await page.locator('#tempChart').count(),0,'O gráfico antigo foi removido');
 assert.equal(await page.locator('#pressure').count(),0);
 assert.equal(await page.locator('#dew').count(),0);
 const previewColor=await page.locator('.meteo-preview').evaluate(el=>getComputedStyle(el).backgroundColor);
 assert.equal(previewColor,'rgb(255, 255, 255)','Meteograma deve ter fundo branco');
 assert.equal(await page.locator('#meteoSmallSvg rect').first().getAttribute('fill'),'#ffffff','SVG deve ter fundo branco');
 await page.locator('#meteoPreview').click();
 assert.equal(await page.locator('#meteoDialog').getAttribute('aria-modal'),'true');
 assert.equal(await page.locator('#meteoDialog').isVisible(),true);
 assert.equal(await page.locator('.meteo-modal').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(255, 255, 255)','Ampliação deve ter fundo branco');

 await page.locator('#meteoNext').click();
 assert.equal(await page.locator('#meteoTimeSlider').inputValue(),'1');
 await page.keyboard.press('ArrowRight');
 assert.equal(await page.locator('#meteoTimeSlider').inputValue(),'2');
 await page.keyboard.press('Escape');
 assert.equal(await page.locator('#meteoDialog').isVisible(),false);
 assert.equal(await page.locator('a#openSkewT').getAttribute('href'),'./laboratorio.html?embedded=1');

 assert.doesNotMatch(await page.locator('#summary').innerText(),/idx is not defined/);
 await page.locator('#place').selectOption('Porto');
 await page.waitForFunction(()=>document.getElementById('meteoInfo')?.textContent.includes('Porto · ECMWF IFS'));
 assert.match(await page.locator('#meteoModalTitle').innerText(),/Porto/);
 assert.match(await page.locator('#meteoSmallSvg').textContent(),/10°/);
 await page.locator('#place').selectOption('Madeira');
 await page.waitForFunction(()=>document.getElementById('meteoInfo')?.textContent.includes('Funchal · ECMWF IFS'));
 await page.locator('[data-island="1"]').click();
 await page.waitForFunction(()=>document.getElementById('meteoInfo')?.textContent.includes('Porto Santo · ECMWF IFS'));
 assert.match(await page.locator('#meteoModalTitle').innerText(),/Porto Santo/);
 await page.locator('#place').selectOption('Açores');
 await page.waitForFunction(()=>document.getElementById('meteoInfo')?.textContent.includes('Terceira \/ Lajes · ECMWF IFS'));
 assert.match(await page.locator('#meteoSmallSvg').textContent(),/16°/);
 await page.locator('#place').selectOption('Lisboa');
 await page.waitForFunction(()=>document.getElementById('meteoInfo')?.textContent.includes('Lisboa · ECMWF IFS'));
 await page.locator('[data-tab="precipGust"]').click();
 await page.locator('#openSkewT').click();
 assert.equal(await page.locator('#skewDialog').isVisible(),true,'Skew-T abre no portal sem navegar');
 assert.match(page.url(),/index.html/);
 const embedded=page.frameLocator('#skewFrame');
 await embedded.locator('#hodograph circle').first().waitFor({timeout:20000});
 assert.equal(await embedded.locator('#skew').isVisible(),true);
 assert.equal(await embedded.locator('#hodograph circle').count()>3,true);
 const first=await embedded.locator('#hodograph line').last().getAttribute('x2');
 await embedded.locator('#city').selectOption('Porto');
 assert.match(await embedded.locator('#validSounding').innerText(),/Porto/);
 const second=await embedded.locator('#hodograph line').last().getAttribute('x2');
 assert.notEqual(first,second,'Hodógrafo muda quando selecionamos Porto');
 await embedded.locator('#skewNext').click();
 assert.equal(await embedded.locator('#skewSlider').inputValue(),'1');
 await embedded.locator('#skewNext').focus();
 await page.keyboard.press('Escape');
 await page.waitForFunction(()=>document.getElementById('skewDialog')?.hidden===true,{timeout:3000});
 assert.equal(await page.locator('#skewDialog').isVisible(),false,'Esc fecha o modal mesmo com foco no iframe');
 assert.equal(await page.locator('#meteoDialog').isVisible(),false,'Meteograma permanece independente');
 await page.locator('#ecmwfSlider').fill('0');
 await page.locator('#ecmwfNext').focus();
 await page.keyboard.press('ArrowRight');
 assert.equal(await page.locator('#ecmwfSlider').inputValue(),'1','Setas sem focar diretamente o cursor de Produtos');
 await page.keyboard.press('Home');
 assert.equal(await page.locator('#ecmwfSlider').inputValue(),'0');
 await page.locator('#ecmwfSlider').focus();
 await page.keyboard.press('ArrowRight');
 assert.equal(await page.locator('#ecmwfSlider').inputValue(),'1');
 await page.keyboard.press('End');
 assert.equal(await page.locator('#ecmwfSlider').inputValue(),'15');
 await page.keyboard.press('Home');
 assert.equal(await page.locator('#ecmwfSlider').inputValue(),'0');
 await page.locator('[data-tab="overview"]').click();
 assert.ok(calls.some(x=>x>40)&&calls.some(x=>x<34)&&calls.some(x=>x>38&&x<39),'ECMWF requests must use regional coordinates');

 // F5 deve preservar cada separador (nao apenas a Sintese).
 for(const tab of ['overview','precipGust','models','aerodromes','synop']){
  await page.locator('[data-tab="'+tab+'"]').click();
  if(tab==='overview')assert.equal(new URL(page.url()).searchParams.get('tab'),null);
  else assert.equal(new URL(page.url()).searchParams.get('tab'),tab);
  await page.reload({waitUntil:'domcontentloaded'});
  assert.equal(await page.locator('#'+tab).isVisible(),true,'F5 deve preservar '+tab);
  assert.equal(await page.locator('[data-tab="'+tab+'"]').getAttribute('class'),'tab active');
 }
 await page.goto('http://127.0.0.1:8765/index.html?tab=precipGust',{waitUntil:'domcontentloaded'});
 assert.equal(await page.locator('#precipGust').isVisible(),true,'Link direto Produtos');
 await page.goto('http://127.0.0.1:8765/laboratorio.html?tab=skewt',{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>document.getElementById('step')?.options.length===16,{timeout:20000});
 await page.reload({waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>document.getElementById('step')?.options.length===16,{timeout:20000});
 assert.equal(await page.locator('#skew').isVisible(),true,'F5 deve preservar pagina Skew-T');
 assert.equal(await page.locator('header .brand h1').innerText(),'MeteoFox');
 assert.equal(await page.locator('#brandProdutos').getAttribute('href'),'./index.html?tab=precipGust');
 assert.equal(await page.locator('nav.tabs .tab').count(),5);
 assert.equal(await page.locator('nav.tabs .tab.active').innerText(),'▤ Produtos');
 assert.equal(await page.locator('.skew-scroll').evaluate(x=>getComputedStyle(x).backgroundColor),'rgb(255, 255, 255)');
 assert.equal(await page.locator('body').evaluate(x=>getComputedStyle(x).color),'rgb(35, 54, 74)','Texto da página Skew-T deve ser escuro');
 assert.equal(await page.locator('main .card').first().evaluate(x=>getComputedStyle(x).backgroundColor),'rgb(255, 255, 255)','Cartões Skew-T devem ser brancos');
 assert.equal(await page.locator('body').evaluate(x=>getComputedStyle(x).backgroundImage),'none','Skew-T sem gradiente azul na página');
 assert.equal(await page.locator('header .topright .pill').evaluate(x=>getComputedStyle(x).backgroundColor),'rgb(255, 255, 255)','Cabeçalho Skew-T também deve ter fundo branco');

 const brandHref=await page.locator('#brandProdutos').getAttribute('href');
 await page.locator('#brandProdutos').click();
 await page.waitForURL('**/index.html?tab=precipGust');
 assert.equal(await page.locator('[data-tab="precipGust"]').getAttribute('class'),'tab active');
 assert.equal(await page.locator('#precipGust').isVisible(),true);
 await page.goto('http://127.0.0.1:8765/laboratorio.html?tab=skewt',{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>document.getElementById('step')?.options.length===16,{timeout:20000});

 assert.equal(await page.locator('#skew circle').count()>10,true);
 assert.equal(await page.locator('#hodograph circle').count()>3,true,'Hodógrafo previsto deve estar presente no laboratório');
 assert.equal(await page.locator('.hodo-scroll').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(255, 255, 255)');
 assert.equal(await page.locator('.skew-scroll').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(255, 255, 255)','Skew-T deve ter fundo branco');
 await page.locator('#skewPrev').focus();
 await page.keyboard.press('ArrowRight');
 assert.equal(await page.locator('#skewSlider').inputValue(),'1','Skew-T deve responder com botão focado');
 await page.keyboard.press('Home');
 assert.equal(await page.locator('#skewSlider').inputValue(),'0');
 await page.locator('#skewSlider').focus();
 await page.keyboard.press('ArrowRight');
 assert.equal(await page.locator('#skewSlider').inputValue(),'1');
 await page.keyboard.press('Home');
 assert.equal(await page.locator('#skewSlider').inputValue(),'0');
 await page.locator('#skewNext').click();
 assert.equal(await page.locator('#skewSlider').inputValue(),'1');
 await page.keyboard.press('ArrowRight');
 assert.equal(await page.locator('#skewSlider').inputValue(),'2');
 await page.locator('#city').selectOption('Beja');
 assert.match(await page.locator('#validSounding').innerText(),/Beja/);
 await page.locator('#skewPrev').click();
 assert.equal(await page.locator('#skewSlider').inputValue(),'1');
 assert.deepEqual(errors,[],'Sem erros JavaScript inesperados');
 console.log('MeteoFox: Meteograma compacto/ampliado, cronologia Skew-T, navegação e dados ECMWF OK');
}finally{await browser.close();}
